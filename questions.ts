const opts = (labels: string[], shapes?: Shape[]): Question['options'] => labels.map((label, i) => ({ id: optionIds[i], label, ...(shapes ? { shape: shapes[i] } : {}) }));
const arrow = (rotation: number, dot?: number): Shape => ({ kind: 'arrow', rotation, ...(dot === undefined ? {} : { dot }) });
const dots = (count: number): Shape => ({ kind: 'dots', count });
const polygon = (sides: number): Shape => ({ kind: 'polygon', sides });
const cells = (...filled: number[]): Shape => ({ kind: 'cells', filled });

